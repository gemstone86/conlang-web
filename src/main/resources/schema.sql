CREATE TABLE IF NOT EXISTS users (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username VARCHAR(64) NOT NULL UNIQUE,
  pw_hash VARCHAR(256) NOT NULL,
  salt VARCHAR(64) NOT NULL,
  is_admin BOOLEAN NOT NULL DEFAULT FALSE,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS reset_codes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  code_hash VARCHAR(128) NOT NULL,
  expires TIMESTAMP NOT NULL
);
CREATE TABLE IF NOT EXISTS worlds (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name VARCHAR(200) NOT NULL,
  owner_id BIGINT NOT NULL REFERENCES users(id)
);
CREATE TABLE IF NOT EXISTS languages (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  world_id BIGINT NOT NULL REFERENCES worlds(id) ON DELETE CASCADE,
  owner_id BIGINT NOT NULL REFERENCES users(id),
  name VARCHAR(200) NOT NULL,
  parent_id BIGINT NULL REFERENCES languages(id),
  split_year INT NULL,
  classes VARCHAR(100000),
  erosion VARCHAR(100000),
  erosion_target INT NOT NULL DEFAULT 0,
  ipa_map VARCHAR(100000),
  grammar VARCHAR(100000)
);
CREATE TABLE IF NOT EXISTS shares (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  scope VARCHAR(16) NOT NULL,
  target_id BIGINT NOT NULL,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  level VARCHAR(16) NOT NULL,
  auto_approve BOOLEAN NOT NULL DEFAULT FALSE,
  UNIQUE (scope, target_id, user_id)
);
CREATE TABLE IF NOT EXISTS words (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  gloss VARCHAR(400) NOT NULL,
  pos VARCHAR(64),
  build VARCHAR(64),
  form VARCHAR(400) NOT NULL,
  year INT NOT NULL DEFAULT 0,
  notes VARCHAR(100000)
);
CREATE TABLE IF NOT EXISTS word_overrides (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id BIGINT NOT NULL REFERENCES words(id) ON DELETE CASCADE,
  lang_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  year INT NOT NULL,
  form VARCHAR(400) NOT NULL
);
CREATE TABLE IF NOT EXISTS rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  year INT NOT NULL,
  ord INT NOT NULL DEFAULT 0,
  name VARCHAR(200),
  pattern VARCHAR(1000) NOT NULL,
  replacement VARCHAR(1000) NOT NULL DEFAULT '',
  note VARCHAR(100000)
);
CREATE TABLE IF NOT EXISTS changes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  author_id BIGINT NOT NULL REFERENCES users(id),
  entity VARCHAR(32) NOT NULL,
  action VARCHAR(16) NOT NULL,
  entity_id BIGINT NULL,
  payload VARCHAR(100000),
  status VARCHAR(16) NOT NULL DEFAULT 'PENDING',
  decided_by BIGINT NULL,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE IF NOT EXISTS edit_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  user_id BIGINT NOT NULL REFERENCES users(id),
  entity VARCHAR(32) NOT NULL,
  action VARCHAR(16) NOT NULL,
  entity_id BIGINT NOT NULL,
  before_json VARCHAR(100000),
  after_json VARCHAR(100000),
  undone BOOLEAN NOT NULL DEFAULT FALSE,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS word_forms (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id BIGINT NOT NULL REFERENCES words(id) ON DELETE CASCADE,
  label VARCHAR(64) NOT NULL,
  form VARCHAR(400) NOT NULL,
  year INT NULL
);
ALTER TABLE languages ADD COLUMN IF NOT EXISTS def_suffix VARCHAR(64);
ALTER TABLE languages ADD COLUMN IF NOT EXISTS syllable_shape VARCHAR(200);

CREATE TABLE IF NOT EXISTS grammar_sections (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  title VARCHAR(400) NOT NULL,
  headings VARCHAR(2000),
  ord INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS grammar_entries (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  category VARCHAR(400) NOT NULL,
  name VARCHAR(2000),
  c1 VARCHAR(4000), c2 VARCHAR(4000), c3 VARCHAR(4000), c4 VARCHAR(4000), c5 VARCHAR(4000), c6 VARCHAR(4000),
  year INT NULL,
  ord INT NOT NULL DEFAULT 0
);
CREATE TABLE IF NOT EXISTS phonemes (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  symbol VARCHAR(40) NOT NULL,
  kind VARCHAR(16) NOT NULL,
  row_label VARCHAR(200),
  col_label VARCHAR(200),
  notes VARCHAR(2000),
  year INT NULL,
  year_to INT NULL
);

CREATE TABLE IF NOT EXISTS form_rules (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  label VARCHAR(64) NOT NULL,
  pos VARCHAR(200),
  placement VARCHAR(16) NOT NULL DEFAULT 'suffix',
  affix VARCHAR(100) NOT NULL,
  cond_re VARCHAR(1000),
  hiatus INT NOT NULL DEFAULT 0,
  year INT NULL,
  ord INT NOT NULL DEFAULT 0
);

ALTER TABLE form_rules ADD COLUMN IF NOT EXISTS affix_word_id BIGINT NULL;

CREATE TABLE IF NOT EXISTS app_log (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  ts TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  lvl VARCHAR(8) NOT NULL,
  category VARCHAR(32) NOT NULL,
  username VARCHAR(64),
  request VARCHAR(400),
  status INT NULL,
  message VARCHAR(4000),
  detail VARCHAR(100000)
);

CREATE TABLE IF NOT EXISTS word_meanings (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id BIGINT NOT NULL REFERENCES words(id) ON DELETE CASCADE,
  lang_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  year INT NOT NULL,
  mode VARCHAR(10) NOT NULL,
  meaning VARCHAR(400) NOT NULL
);
CREATE TABLE IF NOT EXISTS sentences (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  year INT NOT NULL,
  source VARCHAR(4000) NOT NULL,
  translation VARCHAR(2000),
  notes VARCHAR(4000)
);
ALTER TABLE sentences ADD COLUMN IF NOT EXISTS group_no INT NULL;
ALTER TABLE sentences ADD COLUMN IF NOT EXISTS sub_no INT NULL;
ALTER TABLE sentences ADD COLUMN IF NOT EXISTS kind VARCHAR(100) NULL;
ALTER TABLE form_rules ADD COLUMN IF NOT EXISTS grp VARCHAR(100) NULL;
ALTER TABLE words ADD COLUMN IF NOT EXISTS ref_word_id BIGINT NULL;
ALTER TABLE words ADD COLUMN IF NOT EXISTS loan_word_id BIGINT NULL;

-- Missing words: meanings a language has no word for yet (the Missing words tab)
CREATE TABLE IF NOT EXISTS missing_words (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  gloss VARCHAR(400) NOT NULL,
  pos VARCHAR(64),
  notes VARCHAR(4000),
  created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Claude connector keys (com.hub.ConnectorKeys): each one lets the connector at /mcp/<key> read as one account
CREATE TABLE IF NOT EXISTS connector_keys (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  label VARCHAR(200),
  key_hash VARCHAR(128) NOT NULL UNIQUE,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  last_used TIMESTAMP NULL,
  calls BIGINT NOT NULL DEFAULT 0
);

-- Sound change tags (comma separated) and the tags switched off in a language (and its branches)
ALTER TABLE rules ADD COLUMN IF NOT EXISTS tags VARCHAR(400) NULL;
ALTER TABLE languages ADD COLUMN IF NOT EXISTS off_tags VARCHAR(2000) NULL;

-- Saved versions of a language's sound changes (com.conlangs.web.RuleVersions); data: {"rules": [...], "off_tags": "..."}
CREATE TABLE IF NOT EXISTS rule_versions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  name VARCHAR(200) NOT NULL,
  note VARCHAR(4000),
  created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  rule_count INT NOT NULL DEFAULT 0,
  data VARCHAR(1000000) NOT NULL
);

-- Lost words: a word is no longer used in a language from a year (and branches that split off after it never get it)
CREATE TABLE IF NOT EXISTS word_losses (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  word_id BIGINT NOT NULL REFERENCES words(id) ON DELETE CASCADE,
  lang_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  year INT NOT NULL,
  note VARCHAR(400)
);

-- When each account last logged in (shown on the admin dashboard)
ALTER TABLE users ADD COLUMN IF NOT EXISTS last_login TIMESTAMP NULL;

-- Public languages: anyone (even without logging in) can read them; with public_suggestions anyone logged in can
-- suggest changes, which wait for the owner's approval
ALTER TABLE languages ADD COLUMN IF NOT EXISTS is_public BOOLEAN DEFAULT FALSE NOT NULL;
ALTER TABLE languages ADD COLUMN IF NOT EXISTS public_suggestions BOOLEAN DEFAULT FALSE NOT NULL;

-- Texts: longer pieces (a story, a prayer) in the sentence builder's notation, shown at several years side by side
CREATE TABLE IF NOT EXISTS texts (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  language_id BIGINT NOT NULL REFERENCES languages(id) ON DELETE CASCADE,
  title VARCHAR(200) NOT NULL,
  lines_json VARCHAR(200000) NOT NULL,
  years VARCHAR(200),
  notes VARCHAR(4000),
  created_by BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  updated TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- Notifications shown under the bell (com.hub.Notifications)
CREATE TABLE IF NOT EXISTS notifications (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind VARCHAR(32) NOT NULL,
  language_id BIGINT NULL REFERENCES languages(id) ON DELETE CASCADE,
  actor_id BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
  text VARCHAR(1000) NOT NULL,
  link VARCHAR(400),
  times INT NOT NULL DEFAULT 1,
  created TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
  seen BOOLEAN NOT NULL DEFAULT FALSE
);
CREATE INDEX IF NOT EXISTS idx_notifications_user ON notifications(user_id, seen);
