    /** Changes made in the app since a release's height map: applied and undone suggestions, in order. */
    public record HeightOp(int rev, boolean undo, Suggestion s) {}

    public List<HeightOp> heightOpsSince(long mapId, int sinceRev) {
        List<Long> ids = tx(c -> {
            List<Long> r = new ArrayList<>();
            try (PreparedStatement ps = prep(c, "SELECT id FROM height_suggestions WHERE map_id = ? AND (rev_applied > ? OR rev_undone > ?)", mapId, sinceRev, sinceRev);
                 ResultSet rs = ps.executeQuery()) {
                while (rs.next()) r.add(rs.getLong(1));
            }
            return r;
        });
        List<HeightOp> ops = new ArrayList<>();
        for (long id : ids) {
            Suggestion s = suggestion(mapId, id);
            if (s.revApplied() != null && s.revApplied() > sinceRev) ops.add(new HeightOp(s.revApplied(), false, s));
            if (s.revUndone() != null && s.revUndone() > sinceRev) ops.add(new HeightOp(s.revUndone(), true, s));
        }
        ops.sort(Comparator.comparingInt(HeightOp::rev));
        return ops;
    }

