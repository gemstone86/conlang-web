import { chromium } from 'playwright';
const B = 'http://localhost:8080', problems = [];
const browser = await chromium.launch(); const page = await browser.newPage();
page.on('pageerror', e => problems.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error') problems.push('console: ' + m.text()); });
page.on('response', r => { if (r.status() >= 400 && r.url().startsWith(B) && !r.url().endsWith('/api/auth/me')) problems.push('HTTP ' + r.status() + ' ' + r.url()); });
page.on('dialog', d => d.accept('Ygg'));
const text = async sel => (await page.textContent(sel)).replace(/\s+/g, ' ').trim();
await page.goto(B + '/rune/'); await page.waitForURL(/next=/);
await page.click('#authSwitch'); await page.fill('#u', 'Gemstone'); await page.fill('#p', 'secret-pass'); await page.click('#authSubmit');
await page.waitForURL(B + '/rune/'); await page.waitForSelector('[data-act=newWorld]');
await page.click('[data-act=newWorld]'); await page.waitForTimeout(800);
const r = await page.evaluate(async () => {
  const w = (await (await fetch('/rune/api/worlds')).json())[0];
  const l = await (await fetch('/rune/api/languages', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ worldId: w.id, name: 'Proto' }) })).json();
  await fetch('/rune/api/languages/' + l.id + '/sentences', { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify({ source: '(moon) (star)', year: 0, translation: 'Moon star.' }) });
  return l.id;
});
await page.reload(); await page.waitForSelector('#side'); await page.click('#side >> text=Proto'); await page.waitForSelector('[data-act=tab][data-t=missing]');
await page.click('[data-act=tab][data-t=missing]'); await page.waitForSelector('#m_gloss');
console.log('TAB:', (await text('#tabbody')).slice(0, 400));
await page.fill('#m_gloss', 'fire'); await page.fill('#m_pos', 'noun'); await page.click('[data-act=missAdd]'); await page.waitForTimeout(600);
await page.click('details summary'); await page.fill('#m_bulk', 'stone; noun\nfire\nto forgive; verb; later'); await page.click('[data-act=missBulk]'); await page.waitForTimeout(800);
console.log('AFTER ADD:', await text('#msg'));
await page.click('[data-act=missMark][data-g=moon]'); await page.waitForTimeout(600);
console.log('LIST:', (await text('#tabbody')).replace(/.*?Missing words \(/, 'Missing words (').slice(0, 400));
await page.click('[data-act=missCoin][data-g=fire]'); await page.waitForSelector('#w_gloss');
console.log('COIN prefill:', await page.inputValue('#w_gloss'), '/', await page.inputValue('#w_pos'), '| msg:', await text('#msg'));
await page.fill('#w_form', 'pira'); await page.click('[data-act=addWord]'); await page.waitForTimeout(800);
await page.click('[data-act=tab][data-t=missing]'); await page.waitForSelector('#m_gloss');
console.log('AFTER COIN:', (await text('#tabbody')).replace(/.*?Missing words \(/, 'Missing words (').slice(0, 300));
await page.click('[data-act=missClear]'); await page.waitForTimeout(600); console.log('CLEAR:', await text('#msg'));
await browser.close();
console.log(problems.length ? 'PROBLEMS:\n' + problems.join('\n') : 'NO PROBLEMS'); process.exit(problems.length ? 1 : 0);
