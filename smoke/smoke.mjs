import { chromium } from 'playwright';
import XLSX from 'xlsx';
const wb = XLSX.utils.book_new();
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet([['dictionary', 'elven', 'build', 'year', 'type'], ['water', 'ata', 'root', '0', 'noun'], ['fire', 'pira', 'root', '0', 'noun']]), 'Ygg Elven dict');
const g = []; g[0] = ['Name', 'Alviska']; g[8] = ['Grammar', 'order', 'example']; g[9] = ['Basic order', 'SOV', 'I water see']; g[11] = ['Tenses', 'suffix', 'use']; g[12] = ['Past', '-ta', 'finished'];
for (let i = 0; i < g.length; i++) if (!g[i]) g[i] = [];
XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(g), 'Ygg Elven');
XLSX.writeFile(wb, 'alviska.xlsx');
const B = 'http://localhost:8080', problems = [];
const browser = await chromium.launch(); const page = await browser.newPage({ viewport: { width: 1400, height: 1000 } });
page.on('pageerror', e => problems.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error' && !/409/.test(m.text())) problems.push('console: ' + m.text()); });
page.on('response', r => { if (r.status() >= 400 && r.status() !== 409 && r.url().startsWith(B) && !r.url().endsWith('/api/auth/me')) problems.push('HTTP ' + r.status() + ' ' + r.url()); });
page.on('dialog', d => { console.log('DIALOG:', d.message().slice(0, 90)); d.accept(); });
const text = async sel => (await page.textContent(sel)).replace(/\s+/g, ' ').trim();
await page.goto(B + '/'); await page.click('#authSwitch'); await page.fill('#u', 'Gemstone'); await page.fill('#p', 'secret-pass'); await page.click('#authSubmit'); await page.waitForSelector('#inView:not([hidden])');
await page.evaluate(async () => {
  const j = (u, b) => fetch(u, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(b) }).then(r => r.json());
  const w = await j('/rune/api/worlds', { name: 'Ygg' }); await j('/rune/api/languages', { worldId: w.id, name: 'Alviska' });
});
await page.goto(B + '/rune/'); await page.waitForSelector('#side'); await page.click('#side >> text=Alviska');
await page.click('[data-act=tab][data-t=grammar]'); await page.waitForSelector('details.card summary:has-text("Import from Excel")');
await page.click('details.card summary:has-text("Import from Excel")');
await page.setInputFiles('#gx_file', 'alviska.xlsx');
await page.click('[data-act=excelDict]'); await page.waitForTimeout(1500); console.log('DICT:', await text('#msg'));
await page.click('[data-act=excelGrammar]'); await page.waitForTimeout(1500); console.log('GRAMMAR:', await text('#msg'));
console.log('GRAMMAR TAB has rows:', (await text('#tabbody')).includes('SOV'));
await page.click('details.card summary:has-text("Import from Excel")').catch(() => {});
if (!(await page.isVisible('#gx_file'))) await page.click('details.card summary:has-text("Import from Excel")');
await page.setInputFiles('#gx_file', 'alviska.xlsx'); await page.click('[data-act=excelGrammar]'); await page.waitForTimeout(1500); console.log('AGAIN:', await text('#msg'));
await page.click('[data-act=tab][data-t=dict]'); await page.waitForTimeout(800); console.log('DICTIONARY has water:', (await text('#tabbody')).includes('ata'));
await page.click('[data-act=tab][data-t=bulk]'); console.log('BULK card:', await page.isVisible('details.card summary:has-text("Import from Excel")'));
await browser.close();
console.log(problems.length ? 'PROBLEMS:\n' + problems.join('\n') : 'NO PROBLEMS'); process.exit(problems.length ? 1 : 0);
