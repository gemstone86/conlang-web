import { chromium } from 'playwright';
const B = 'http://localhost:8080', problems = [];
const browser = await chromium.launch();
const page = await (await browser.newContext({ viewport: { width: 1400, height: 1000 } })).newPage();
page.on('pageerror', e => problems.push('pageerror: ' + e.message));
page.on('console', m => { if (m.type() === 'error') problems.push('console: ' + m.text()); });
page.on('dialog', d => d.accept());
const text = async sel => (await page.textContent(sel)).replace(/\s+/g, ' ').trim();
await page.goto(B + '/'); await page.click('#authSwitch'); await page.fill('#u', 'Gemstone'); await page.fill('#p', 'secret-pass'); await page.click('#authSubmit'); await page.waitForSelector('#inView:not([hidden])');
const ids = await page.evaluate(async () => {
  const j = (u, b) => fetch(u, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(b) }).then(r => r.json());
  const w = await j('/rune/api/worlds', { name: 'Ygg' }); const l = await j('/rune/api/languages', { worldId: w.id, name: 'Elven' });
  const e = (entity, payload) => j('/rune/api/languages/' + l.id + '/edit', { entity, action: 'CREATE', payload });
  const tal = await e('word', { gloss: 'stone', pos: 'noun', form: 'tal', year: 10 });
  for (const [grp, label, affix] of [['number', 'plural', 'i'], ['number', 'dual', 't'], ['case', 'genitive', 'o'], ['definiteness', 'definite', 'n']])
    await e('formrule', { grp, label, pos: 'noun', placement: 'suffix', affix });
  return { l: l.id, tal: tal.id };
});
await page.goto(B + '/rune/?lang=' + ids.l + '&tab=forms'); await page.waitForSelector('#sg_list');
console.log('ORDER CARD:', await text('#sg_list'), '|', (await text('#sg_list + p')));
await page.click('#sg_list li:nth-child(3) [data-d="-1"]'); await page.click('#sg_list li:nth-child(2) [data-d="-1"]');
console.log('AFTER MOVES:', await text('#sg_list'));
await page.click('[data-act=sgSave]'); await page.waitForTimeout(800); await page.waitForSelector('#sg_list');
console.log('SAVED:', await text('#sg_list'), '|', await text('#sg_list + p'));
await page.click('[data-act=tab][data-t=dict]'); await page.waitForSelector('#wbody a[data-act=openWord]');
await page.click('#wbody a[data-act=openWord]'); await page.waitForSelector('#w_para');
await page.click('#w_para summary'); await page.waitForSelector('table.paradigm');
console.log('ALL FORMS:', await text('#w_parabody'));
await page.fill('#w_parayear', '5'); await page.click('[data-act=paraYear]'); await page.waitForTimeout(800);
console.log('AT YEAR 5:', (await text('table.paradigm')).slice(0, 300));
await page.keyboard.press('Escape');
await page.click('[data-act=tab][data-t=sentences]'); await page.waitForSelector('#s_src');
await page.fill('#s_src', '(stone-plural-genitive-definite)'); await page.fill('#s_year', '100'); await page.click('[data-act=sentBuild]'); await page.waitForTimeout(800);
console.log('SENTENCE:', await text('#tabbody table.interlinear'));
await browser.close();
console.log(problems.length ? 'PROBLEMS:\n' + problems.join('\n') : 'NO PROBLEMS'); process.exit(problems.length ? 1 : 0);
